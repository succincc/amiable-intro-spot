-- ============================================================================
-- A list of large US employers to pull jobs from
--
-- The hard part of a list like this is not the names, it is that every entry
-- has to resolve to something we can actually fetch from. "jobs.target.com"
-- is a Workday tenant, "careers.ibm.com" is not, and which pod a tenant sits
-- on (wd1, wd5, wd103) cannot be guessed at all. A hand-written list of
-- tenant/site/pod triples would be wrong in dozens of places and each wrong
-- one becomes a company row that silently returns nothing.
--
-- So this stores the one thing that is easy to be right about — the company's
-- own careers address — and the verifier resolves the rest by following where
-- that address actually goes. Entries it cannot resolve are marked and say
-- why, rather than being quietly dropped or quietly broken.
--
-- Nothing here is added to `companies` until it has been checked and has
-- actually returned jobs.
-- ============================================================================

create table if not exists company_candidates (
  id          uuid primary key default gen_random_uuid(),
  name        text not null,
  careers_url text not null unique,
  -- pending | ok | failed | skipped
  status      text not null default 'pending',
  ats         text,
  token       text,
  pod         text,
  site        text,
  resolved_url text,
  note        text,
  checked_at  timestamptz,
  created_at  timestamptz default now()
);

create index if not exists idx_candidates_status on company_candidates(status);

alter table company_candidates enable row level security;
drop policy if exists owner_all on company_candidates;
create policy owner_all on company_candidates for all to authenticated using (true) with check (true);

